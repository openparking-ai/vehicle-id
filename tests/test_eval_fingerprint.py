# --- a synthetic pair set, which is all any of this needs -----------------


@pytest.fixture(scope="module")
def pair_set(tmp_path_factory):
    """Six pairs, TWO of them flat, described once and reused.

    The flat pairs are not decoration: they are what makes the UNMEASURABLE cell
    non-zero, and every assertion about the third outcome would pass vacuously
    without them.

    TWO rather than one, and that is a correction. The split alternates over the
    sorted pair ids, so a single flat pair is always the first id and always
    lands in the FIT half -- leaving the REPORT half, which is where the counts
    the fail-control guards are produced, with nothing unmeasurable in it. The
    control asserted a property of a cell that was structurally zero. Two flat
    pairs put one in each half.
    """
    directory = tmp_path_factory.mktemp("pairs")
    write_synthetic(directory, pairs=6, flat=2)
    index = json.loads((directory / "index.json").read_text())
    images, excluded, _ = harness.load_images(directory, index)
    descriptors = describe_all(images, ORB)
    comparisons = all_comparisons(descriptors)
    return {
        "directory": directory,
        "index": index,
        "descriptors": descriptors,
        "comparisons": comparisons,
        "measured": measure(descriptors, comparisons),
        "pair_ids": sorted(images),
        "split": split_of(sorted(images)),
        "excluded": excluded,
    }


def an_arm(pair_set, term="structure", **constraints):
    settings = {"max_false_match_rate": 0.05, "max_miss_rate": 0.40}
    settings.update(constraints)
    return arm(
        term,
        pair_set["measured"],
        pair_set["comparisons"],
        pair_set["split"],
        pair_set["descriptors"],
        pair_set["pair_ids"],
        **settings,
    )


# --- THREE outcomes, never two -------------------------------------------


@guarantee
def test_the_flat_pair_produces_unmeasurable_comparisons_at_all(pair_set):
    """The control for every assertion below it. If nothing were unmeasurable,
    the cells that separate "nothing matched" from "nothing to match" would be
    zero and a harness that had merged them would still look right."""
    block = an_arm(pair_set)
    unmeasurable = sum(block["distances"][k]["unmeasurable"] for k in (SAME_CAR, DIFFERENT_CAR))
    assert unmeasurable > 0, "no comparison was unmeasurable; the third outcome is untested"


@guarantee
def test_an_unmeasurable_comparison_is_in_neither_of_the_other_two_cells(pair_set):
    """FAIL-CONTROL: an unmeasurable pair counted as a miss, or as a correct reject.

    That one mistake flatters the miss rate AND the false-match rate at the same
    time, which is why it is the defect this harness is most at risk from. The
    check is arithmetic rather than a predicate: for each class, matched plus
    not-matched must equal the MEASURABLE count, and the unmeasurable count must
    sit outside that sum entirely.

    Route the unmeasurable comparisons into `not_matched` and this goes red on
    both classes at once.
    """
    block = an_arm(pair_set)
    assert block["counts"]["available"], "the operating point was refused; nothing to count"

    # Without this the whole test is vacuous: if no REPORT-half comparison were
    # unmeasurable, routing the unmeasurable ones into `not_matched` would move
    # nothing and the assertions below would hold either way.
    reported_unmeasurable = sum(
        block["counts"][klass]["unmeasurable"] for klass in (SAME_CAR, DIFFERENT_CAR)
    )
    assert reported_unmeasurable > 0, (
        "no comparison in the reported half was unmeasurable, so this control "
        "cannot see the defect it names"
    )

    for klass in (SAME_CAR, DIFFERENT_CAR):
        cells = block["counts"][klass]
        total = cells["matched"] + cells["not_matched"]
        # The measurable subset the counts were computed over, taken from the
        # bounds block, which is where a reader gets it from too.
        over = block["bounds_95"][
            "miss_rate" if klass == SAME_CAR else "false_match_rate"
        ]["over"]
        assert total == over, (
            f"{klass}: matched+not_matched is {total} but the counts are stated "
            f"over {over} measurable comparisons -- an unmeasurable comparison "
            "has been counted as one of the other two outcomes"
        )


@guarantee
def test_every_count_is_published_beside_the_number_it_was_computed_over(pair_set):
    """A count with no denominator is not a measurement. The unmeasurable count
    lives INSIDE the distribution block so it cannot be quoted separately from
    the quantiles it was excluded from."""
    block = an_arm(pair_set)
    for klass in (SAME_CAR, DIFFERENT_CAR):
        distribution = block["distances"][klass]
        assert "measurable" in distribution and "unmeasurable" in distribution
        if distribution["measurable"] == 0:
            assert distribution["median"] is None


# --- the split, and the leakage it prevents ------------------------------


@guarantee
def test_the_halves_are_disjoint_and_cover_every_pair(pair_set):
    split = pair_set["split"]
    fit = {p for p, half in split.items() if half == FIT}
    report = {p for p, half in split.items() if half == REPORT}
    assert not (fit & report)
    assert fit | report == set(pair_set["pair_ids"])
    assert fit and report, "one half is empty; there is nothing to fit or nothing to report"


@guarantee
def test_the_split_is_the_same_every_run(pair_set):
    """Deterministic, so a receipt can be checked against a re-run."""
    assert split_of(pair_set["pair_ids"]) == pair_set["split"]
    assert split_of(list(reversed(pair_set["pair_ids"]))) == pair_set["split"]


@guarantee
def test_the_threshold_does_not_move_when_the_report_half_changes(pair_set):
    """FAIL-CONTROL: the threshold fitted on the pairs the counts are reported over.

    The strongest form of the check, because it does not inspect the code: it
    perturbs every REPORT-half distance to nonsense and requires the chosen
    threshold to be identical. Fit on all the pairs instead of on the fit half
    and this goes red immediately -- the perturbed values change the answer.
    """
    baseline = an_arm(pair_set)
    assert baseline["counts"]["available"]

    split = pair_set["split"]
    poisoned = {}
    for (left, right), comparison in pair_set["measured"].items():
        if split[left[0]] == REPORT and split[right[0]] == REPORT:
            poisoned[(left, right)] = _replace_term(comparison, "structure", 999.0)
        else:
            poisoned[(left, right)] = comparison

    after = arm(
        "structure", poisoned, pair_set["comparisons"], split,
        pair_set["descriptors"], pair_set["pair_ids"],
        max_false_match_rate=0.05, max_miss_rate=0.40,
    )
    assert after["operating_point"]["refused"] is False, (
        "the poisoned report half changed whether an operating point exists at "
        "all, so the threshold was fitted on data it should never have seen"
    )
    assert after["operating_point"]["threshold"] == baseline["operating_point"]["threshold"], (
        "the chosen threshold moved when only the REPORT half changed"
    )
    # And the control for the control: the COUNTS did move, so the poison was
    # real and the threshold's stability is not because nothing happened.
    assert after["counts"][SAME_CAR] != baseline["counts"][SAME_CAR]


def _replace_term(comparison, term, value):
    from vehicle_id.fingerprint import Comparison

    terms = tuple(
        TermDistance(term=t.term, value=value, measurable=True) if t.term == term else t
        for t in comparison.terms
    )
    return Comparison(kind=comparison.kind, version=comparison.version, terms=terms)


# --- a matcher that says every car is every other car ---------------------


@guarantee
def test_a_matcher_that_matches_everything_gets_no_operating_point(pair_set):
    """FAIL-CONTROL: two different cars forced to match.

    Every comparison at distance zero. There is no threshold that admits the
    same-car pairs and excludes the different-car ones, because they are the
    same number, so the arm must REFUSE and publish no counts. A harness that
    reported "20 matched, 0 missed" here would be reporting a perfect score for
    a matcher with no discrimination at all.

    The AUC is checked too: at 0.5 it says exactly this, threshold-free, without
    needing the refusal to have worked.
    """
    forced = {
        key: _replace_term(comparison, "structure", 0.0)
        for key, comparison in pair_set["measured"].items()
    }
    block = arm(
        "structure", forced, pair_set["comparisons"], pair_set["split"],
        pair_set["descriptors"], pair_set["pair_ids"],
        max_false_match_rate=0.01, max_miss_rate=0.20,
    )
    assert block["separation"]["auc"] == pytest.approx(0.5)
    assert block["operating_point"]["refused"] is True
    assert "no threshold satisfies both" in block["operating_point"]["why"]
    assert block["counts"]["available"] is False


@guarantee
def test_a_refused_arm_publishes_the_refusal_and_not_a_table(pair_set):
    """A refusal is a result. It is published with its reasoning, and the counts
    block says it is unavailable rather than being absent -- an absent key reads
    as an oversight, and a reader would go looking for the table."""
    block = an_arm(pair_set, max_false_match_rate=0.0, max_miss_rate=0.0)
    if block["operating_point"]["refused"]:
        assert "why" in block["operating_point"]
        assert block["counts"]["available"] is False
        assert "bounds_95" not in block
    else:
        # The separated case is legitimate on a synthetic set. Then the counts
        # must be there, which is the other half of the same assertion.
        assert block["counts"]["available"] is True


# --- the bounds ----------------------------------------------------------


@guarantee
@pytest.mark.parametrize(
    "k,n,expected",
    [
        (0, 20, 0.1391),      # a perfect run on twenty same-car comparisons
        (0, 760, 0.00393),    # and on the different-car comparisons beside them
        (0, 10, 0.2589),
        (1, 20, 0.2161),
    ],
)
def test_the_bound_is_the_exact_one_and_not_the_rule_of_three(k, n, expected):
    """The numbers the receipt states, computed rather than quoted.

    The rule of three (3/n) is an approximation that holds only at k=0 and only
    for large n, and n here is small on purpose. At k=0, n=20 it says 15.0% and
    the exact answer is 13.9%; at k=1 it says nothing at all. This is
    Clopper-Pearson, by bisection on the binomial CDF.
    """
    assert clopper_pearson_upper(k, n) == pytest.approx(expected, abs=5e-4)


@guarantee
def test_zero_events_does_not_produce_a_bound_of_zero():
    """The whole reason the bounds are published beside the counts. A table of
    zeros that cannot support the decision it is read for is worse than a table
    with a caveat."""
    assert clopper_pearson_upper(0, 20) > 0.13
    assert clopper_pearson_upper(0, 760) > 0.003


@guarantee
def test_the_bound_tightens_as_the_evidence_grows():
    bounds = [clopper_pearson_upper(0, n) for n in (10, 20, 100, 760)]
    assert bounds == sorted(bounds, reverse=True)


@guarantee
def test_the_published_bounds_match_the_counts_they_sit_beside(pair_set):
    """Derived from the same numbers, so a count and its bound cannot disagree."""
    block = an_arm(pair_set)
    assert block["counts"]["available"]
    misses = block["counts"][SAME_CAR]["not_matched"]
    over = block["bounds_95"]["miss_rate"]["over"]
    assert block["bounds_95"]["miss_rate"]["upper"] == pytest.approx(
        clopper_pearson_upper(misses, over)
    )


# --- separation, threshold-free ------------------------------------------


@guarantee
def test_the_auc_is_one_when_every_same_car_distance_is_below_every_other():
    """A known answer, because an AUC computed the wrong way round is a number
    that still looks like an AUC. Written the wrong way round first, and a
    synthetic run reported 0.0000 for a perfectly separating arm."""
    assert auc([0.1, 0.2], [0.8, 0.9]) == 1.0
    assert auc([0.8, 0.9], [0.1, 0.2]) == 0.0
    assert auc([0.5], [0.5]) == 0.5
    assert auc([0.1, 0.9], [0.1, 0.9]) == 0.5
    assert auc([], [0.1]) is None


@guarantee
def test_the_overlap_says_something_the_auc_cannot():
    """Two distributions can have a near-perfect AUC and still touch. The
    overlap is the fraction of different-car distances at or below the largest
    same-car one -- the tail an operating point has to live in."""
    assert overlap([0.1, 0.2], [0.8, 0.9]) == 0.0
    assert overlap([0.1, 0.85], [0.8, 0.9]) == 0.5
    assert overlap([0.1], []) is None


@guarantee
def test_the_quantiles_interpolate_and_answer_none_on_an_empty_sample():
    assert quantile([], 0.5) is None
    assert quantile([1.0], 0.5) == 1.0
    assert quantile([0.0, 1.0], 0.5) == 0.5
    assert quantile([0.0, 1.0, 2.0, 3.0], 0.0) == 0.0
    assert quantile([0.0, 1.0, 2.0, 3.0], 1.0) == 3.0


# --- the tie rate, A5.1 ---------------------------------------------------


@guarantee
def test_the_tie_count_finds_a_candidate_that_is_at_least_as_close(pair_set):
    """A5.1 as arithmetic, on a constructed case.

    Every comparison is put at the same distance, so for each same-car pair
    every other image in the set is exactly as close as its own partner. The
    tie count must then be the whole candidate pool: a system asked to identify
    the vehicle at the exit would have no basis to choose. That is the number
    that decides whether a tie-breaking stage is needed at all.
    """
    flattened = {
        key: _replace_term(comparison, "structure", 0.42)
        for key, comparison in pair_set["measured"].items()
    }
    ties = ties_for("structure", pair_set["descriptors"], flattened, pair_set["pair_ids"])
    assert ties["same_car_pairs_measured"] == len(pair_set["pair_ids"])
    assert ties["pairs_with_no_closer_or_equal_candidate"] == 0
    assert ties["pairs_with_at_least_one"] == len(pair_set["pair_ids"])
    assert ties["histogram"] == {str(ties["candidate_pool_per_pair"]): len(pair_set["pair_ids"])}


@guarantee
def test_a_pair_with_no_competitor_at_all_records_a_tie_count_of_zero(pair_set):
    """The other end, and the control for the test above: on the real synthetic
    distances a well-separated set has pairs whose own distance nothing else
    reaches."""
    ties = ties_for("structure", pair_set["descriptors"], pair_set["measured"],
                    pair_set["pair_ids"])
    assert ties["pairs_with_no_closer_or_equal_candidate"] > 0
    assert ties["candidate_pool_per_pair"] > 0


@guarantee
def test_a_pair_whose_own_comparison_is_unmeasurable_is_excluded_from_the_ties(pair_set):
    """There is no distance for a competitor to be nearer than, so the pair is
    excluded and COUNTED as excluded -- not silently given a tie count of zero,
    which would read as "one clear answer"."""
    ties = ties_for("structure", pair_set["descriptors"], pair_set["measured"],
                    pair_set["pair_ids"])
    assert ties["same_car_pairs_excluded_unmeasurable"] >= 1
    assert (
        ties["same_car_pairs_measured"] + ties["same_car_pairs_excluded_unmeasurable"]
        == len(pair_set["pair_ids"])
    )


