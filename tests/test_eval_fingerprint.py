"""The pair harness: its three outcomes, its split, its bounds and its refusal.

This file is where round A is proven able to fail. The harness's whole output is
a number that a later round's spend is decided on, so the ways it could produce a
flattering one are enumerated and each is planted:

  * an UNMEASURABLE comparison counted as a miss or as a correct reject. That
    single mistake improves both the miss rate and the false-match rate at once,
    which is why it is the first thing checked and why it is checked on the real
    cells rather than on the predicate.
  * a threshold fitted on the pairs the counts are then reported over. Proven by
    perturbing the report half and requiring the chosen threshold NOT to move.
  * a matcher that says every car is every other car, and an operating point
    chosen anyway.
  * a table of zeros read as a guarantee, which is what the bounds are for.
  * a photograph's name reaching the evidence file.

Nothing here needs a photograph, a checkpoint or torch: the pair set is
synthetic, generated by the harness's own `--write-synthetic`, and its numbers
are invented. That is deliberate -- the code, the harness and every control were
required to be provable BEFORE the real photographs exist.
"""

