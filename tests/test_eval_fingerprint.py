@guarantee
def test_a_run_of_real_photographs_would_not_be_marked_synthetic(tmp_path):
    """The flag is read from the index, so a real run cannot inherit it -- and a
    synthetic number can never be quoted later as the answer."""
    photos = tmp_path / "pairs"
    write_synthetic(photos, pairs=3, flat=0)
