def a_representative_object() -> dict:
    return build_output(
        arms={"structure": {"separation": {"auc": 1.0}}},
        kind=ORB,
        n_pairs=6,
        n_images=12,
        excluded_pairs=0,
        comparison_counts={SAME_CAR: 6, DIFFERENT_CAR: 60, "total": 66},
        split_counts={"fit_pairs": 3, "report_pairs": 3, "disjoint": True, "note": "n"},
        synthetic=True,
        descriptor_version=1,
        cv2_version="5.0.0",
        python_version="3.12.14",
        package_version="0.1.0",
        harness_digest="e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        guard_digest="da39a3ee5e6b4b0d3255bfef95601890afd80709",
        timestamp="2026-09-06T15:04:05+03:00",
    )


def the_real_object(pair_set) -> dict:
    arms = {term: an_arm(pair_set, term) for term in TERM_NAMES}
    obj = a_representative_object()
    obj["arms"] = arms
    return obj


